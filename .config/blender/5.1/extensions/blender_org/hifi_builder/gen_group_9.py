def gen_office_sinks(props, sc):
    cleanup_previews()
    if not HiFi_Sinks_VERTS or not HiFi_Sinks_FACES: return None, {}
    
    scaled_verts = [(v[0]*sc, v[1]*sc, v[2]*sc) for v in HiFi_Sinks_VERTS]
    mesh = bpy.data.meshes.new(PREVIEW_PREFIX + "OFFICE_SINKS_mesh")
    mesh.from_pydata(scaled_verts, [], HiFi_Sinks_FACES)
    mesh.update()
    
    obj = bpy.data.objects.new(PREVIEW_PREFIX + "OFFICE_SINKS", mesh)
    bpy.context.collection.objects.link(obj)
    
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    apply_transform(obj)
    
    params = {"type": "OFFICE_SINKS", "unit": props.unit_type}
    return obj, params