def gen_gta_statue(props, sc):
    cleanup_previews()
    
    if not HiFi_GTA_Base_Character_Statue_VERTS or not HiFi_GTA_Base_Character_Statue_FACES:
        print("HiFi GTA Statue Data is empty!")
        return None, {}
        
    scaled_verts = [(v[0]*sc, v[1]*sc, v[2]*sc) for v in HiFi_GTA_Base_Character_Statue_VERTS]
    
    mesh = bpy.data.meshes.new(PREVIEW_PREFIX + "GTA_STATUE_mesh")
    mesh.from_pydata(scaled_verts, [], HiFi_GTA_Base_Character_Statue_FACES)
    mesh.update()
    
    obj = bpy.data.objects.new(PREVIEW_PREFIX + "GTA_STATUE", mesh)
    bpy.context.collection.objects.link(obj)
    
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    apply_transform(obj)
    
    params = {"type": "GTA_STATUE", "unit": props.unit_type}
    return obj, params