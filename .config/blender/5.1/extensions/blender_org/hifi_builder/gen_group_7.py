def gen_ceiling_fan(props, sc):
    cleanup_previews()
    objs = []
    
    if props.fan_show_base and HiFi_Fan_Base_VERTS and HiFi_Fan_Base_FACES:
        scaled_verts = [(v[0]*sc, v[1]*sc, v[2]*sc) for v in HiFi_Fan_Base_VERTS]
        mesh = bpy.data.meshes.new(PREVIEW_PREFIX + "FAN_BASE_mesh")
        mesh.from_pydata(scaled_verts, [], HiFi_Fan_Base_FACES)
        mesh.update()
        obj = bpy.data.objects.new(PREVIEW_PREFIX + "FAN_BASE", mesh)
        bpy.context.collection.objects.link(obj)
        bpy.context.view_layer.objects.active = obj
        obj.select_set(True)
        apply_transform(obj)
        obj.select_set(False)
        objs.append(obj)
        
    if props.fan_show_blades and HiFi_Fan_Blades_VERTS and HiFi_Fan_Blades_FACES:
        scaled_verts = [(v[0]*sc, v[1]*sc, v[2]*sc) for v in HiFi_Fan_Blades_VERTS]
        mesh = bpy.data.meshes.new(PREVIEW_PREFIX + "FAN_BLADES_mesh")
        mesh.from_pydata(scaled_verts, [], HiFi_Fan_Blades_FACES)
        mesh.update()
        obj = bpy.data.objects.new(PREVIEW_PREFIX + "FAN_BLADES", mesh)
        bpy.context.collection.objects.link(obj)
        bpy.context.view_layer.objects.active = obj
        obj.select_set(True)
        apply_transform(obj)
        obj.select_set(False)
        objs.append(obj)

    if not objs:
        return None, {}
        
    params = {"type": "CEILING_FAN", "unit": props.unit_type}
    return objs, params