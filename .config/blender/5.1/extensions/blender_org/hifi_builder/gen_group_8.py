def gen_toilet(props, sc):
    cleanup_previews()
    if not HiFi_Toilet_VERTS or not HiFi_Toilet_FACES: return None, {}
    
    scaled_verts = [(v[0]*sc, v[1]*sc, v[2]*sc) for v in HiFi_Toilet_VERTS]
    mesh = bpy.data.meshes.new(PREVIEW_PREFIX + "TOILET_mesh")
    mesh.from_pydata(scaled_verts, [], HiFi_Toilet_FACES)
    mesh.update()
    
    obj = bpy.data.objects.new(PREVIEW_PREFIX + "TOILET", mesh)
    bpy.context.collection.objects.link(obj)
    
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    apply_transform(obj)
    
    params = {"type": "TOILET", "unit": props.unit_type}
    return obj, params